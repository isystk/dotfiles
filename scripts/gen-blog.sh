#!/bin/bash

# ==============================================================================
# 概要: AIを活用してブログ記事を自動生成する
#
# 動作フロー:
#   1. ブログテンプレートを読み込み
#   2. 引数で受け取った「記事ネタ」とテンプレートを gemini-cli コマンドに渡して生成
# ==============================================================================

# 記事のネタ（引数）を結合して取得
if [ ! -t 0 ]; then
    # 標準入力（パイプ）がある場合
    INPUT_TEXT=$(cat -)
else
    # 引数がある場合
    INPUT_TEXT="$*"
fi

if [ -z "$INPUT_TEXT" ]; then
    echo "⚠️ 記事のネタ（タイトルやキーワード）を引数に指定してください。"
    echo "使用例: $0 'Pythonの基本文法についての初心者向けガイド'"
    exit 1
fi

# AIへのプロンプト構築と生成
echo "🤖 1/2: AIで記事を生成中..."

# 入力データ構築
# 記事ネタとテンプレート、そして制約事項をコンテキストとして渡す
DATA="
テーマ: $INPUT_TEXT

以下のWordPressテーマ（isystk-theme）専用テンプレートの仕様に従って、ブログ記事を作成してください。
指示に含まれていない機能（クラス名）は使用しないでください。

---
$README_TEMPLATE_CONTENT
"

# gemini-cli コマンドの実行
# -t gen-blog は .config/gemini-cli/templates 配下のテンプレート
INITIAL_GEN=$(echo "$DATA" | gemini-cli -t gen-blog)

if [ -z "$INITIAL_GEN" ]; then
    echo "❌ 記事の生成に失敗しました。"
    exit 1
fi

echo "✨ 2/2: 元記事の内容に基づきブラッシュアップ中..."
prompt="
# 指示
以下の「元記事」と「AI生成結果」を比較し、AI生成結果をブラッシュアップしてください。

# 制約事項
1. **既存の構成を維持**: AI生成結果の構成やトーンは原則として維持してください。
2. **不足要素の補完**: 元記事に含まれている重要な情報（コマンド、設定値、ベストプラクティス等）が欠落している場合のみ、適切に追加してください。
3. **正確性の向上**: 技術的な誤りや古い情報の修正。
4. **構成**: 余計な解説は一切禁止。

# データ
## 元記事
$INPUT_TEXT

## AI生成結果
$INITIAL_GEN
"
GENERATED=$(echo -e "$prompt" | gemini-cli)

if [[ -z "$GENERATED" ]]; then
    echo "⚠️ ブラッシュアップに失敗したため、初期生成版を出力します。" >&2
    GENERATED="$INITIAL_GEN"
fi

# 3. 結果のプレビュー
echo -e "\n--- 📝 生成されたブログ記事のプレビュー ---"
echo "----------------------------------------------------------------"
echo "$GENERATED"
echo "----------------------------------------------------------------"

# 4. (オプション) ファイルへの保存
# 日付付きのファイル名で保存したい場合は以下のコメントを外してください
# SAVE_DIR="$HOME/Downloads"
# FILE_NAME="blog_$(date +%Y%m%d_%H%M%S).md"
# echo "$GENERATED" > "$SAVE_DIR/$FILE_NAME"
# echo "✅ 記事を保存しました: $SAVE_DIR/$FILE_NAME"

echo -e "\n✨ 生成が完了しました。"
